# .union() crea un nuevao 
set1 = {1,2,3}
set2 = {4,5,6}

union_set = set1.union(set2)

print(union_set)

# intersection(set2) devolver la intersecion de ambos conjuntos

set3 = {1,2,3,4}
set4 = {3,4,5,6}

intersection_set = set3.intersection(set4)
print(intersection_set)

# diferencia difference(set2) todo loa de set3 pero no interseccion o set4
difference =  set3.difference(set4)
print(difference)


